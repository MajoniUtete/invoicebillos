create or replace function public.set_receipt_total()
returns trigger
language plpgsql
as $$
begin
  new.total = greatest(coalesce(new.subtotal, 0) + coalesce(new.tax, 0) - coalesce(new.discount, 0), 0);
  return new;
end;
$$;

create or replace function public.set_receipt_item_line_total()
returns trigger
language plpgsql
as $$
begin
  new.line_total = coalesce(new.quantity, 0) * coalesce(new.unit_price, 0);
  return new;
end;
$$;

create or replace function public.refresh_receipt_totals(target_receipt_id bigint)
returns void
language plpgsql
as $$
begin
  update public.receipts r
  set subtotal = coalesce((
        select sum(ri.line_total)
        from public.receipt_items ri
        where ri.receipt_id = target_receipt_id
      ), 0)
  where r.id = target_receipt_id;
end;
$$;

create or replace function public.refresh_receipt_totals_from_items()
returns trigger
language plpgsql
as $$
begin
  if tg_op = 'INSERT' then
    perform public.refresh_receipt_totals(new.receipt_id);
    return null;
  end if;

  if tg_op = 'UPDATE' then
    perform public.refresh_receipt_totals(new.receipt_id);
    if old.receipt_id is distinct from new.receipt_id then
      perform public.refresh_receipt_totals(old.receipt_id);
    end if;
    return null;
  end if;

  if tg_op = 'DELETE' then
    perform public.refresh_receipt_totals(old.receipt_id);
    return null;
  end if;

  return null;
end;
$$;

