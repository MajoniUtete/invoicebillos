create table if not exists public.receipts (
  id bigint generated by default as identity primary key,
  receipt_number text not null unique,
  customer_id bigint references public.customers(id) on delete set null,
  receipt_date date not null default current_date,
  currency text not null default 'USD',
  subtotal numeric not null default 0,
  tax numeric not null default 0,
  discount numeric not null default 0,
  total numeric not null default 0,
  payment_method text not null default 'Cash',
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  user_id uuid not null references auth.users(id) on delete cascade,
  constraint receipts_amounts_nonnegative check (subtotal >= 0 and tax >= 0 and discount >= 0 and total >= 0),
  constraint receipts_currency_format check (currency ~ '^[A-Za-z]{3,5}$'),
  constraint receipts_payment_method_valid check (payment_method in ('Cash', 'Card', 'Mobile Money', 'Bank Transfer', 'Other'))
);

create table if not exists public.receipt_items (
  id bigint generated by default as identity primary key,
  receipt_id bigint not null references public.receipts(id) on delete cascade,
  item_name text not null,
  description text,
  quantity numeric not null default 1,
  unit_price numeric not null default 0,
  line_total numeric not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  user_id uuid not null references auth.users(id) on delete cascade,
  constraint receipt_items_quantity_nonnegative check (quantity >= 0),
  constraint receipt_items_unit_price_nonnegative check (unit_price >= 0),
  constraint receipt_items_line_total_nonnegative check (line_total >= 0)
);

